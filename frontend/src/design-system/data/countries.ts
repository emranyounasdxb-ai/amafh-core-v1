export type CountryRecord = {
  code: string;
  name: string;
  nationality: string;
};

export const countryRecords: CountryRecord[] = Object.entries(
  countries.getNames("en", { select: "official" }),
)
  .map(([code, name]) => ({
    code,
    name,
    nationality: nationalityByCode[code] ?? name,
  }))
  .sort((left, right) => left.name.localeCompare(right.name));

export function searchCountryRecords(query: string, records = countryRecords) {
  const term = query.trim().toLowerCase();
  if (!term) return records;
  return records.filter(
    (item) =>
      item.name.toLowerCase().includes(term) ||
      item.nationality.toLowerCase().includes(term) ||
      item.code.toLowerCase().includes(term),
  );
}

export function countryOptions(records = countryRecords) {
  return records.map((item) => ({
    value: item.code,
    label: item.name,
    description: item.code,
    keywords: [item.name, item.nationality, item.code],
  }));
}

export function nationalityOptions(records = countryRecords) {
  return records.map((item) => ({
    value: item.code,
    label: item.nationality,
    description: `${item.name} · ${item.code}`,
    keywords: [item.nationality, item.name, item.code],
  }));
}
